#!/usr/bin/env bun
// P4 artifact 5: execution model over docs/plan/units.yaml.
//
// Checks the routing (every unit routed and tiered; every unit off the matrix carries an execution_reason) and budgets
// Dave's time under the tiered auto-merge rule (ADR 0010, amended 2026-10-20), with the old merge-everything rule as the
// comparison: gates on fan-out units, people checks, recurring weekly work, and his own tasks.
// The minutes are in dave-time.ts, each an assumption until P5's dave_minutes calibrate it; the report names the calibration points.
//
// Run: bun scripts/plan/execution-model.ts [--weeks N] [--write docs/plan/05-execution-model.md]
//   --weeks N   P5 weeks for the recurring rows and the weekly promotion (default 18, artifact 7's likely build length)
//   --weight W  as in critical-path.ts (auto, pert, points, count); 05 stays in points, as approved
// Marker in the target file: <!-- execution-model:report:start --> ... <!-- execution-model:report:end -->

import {
  add,
  APPROVAL_MODE_UNITS,
  batchReadMinutes,
  BOOKKEEPING,
  CI_TRIAGE,
  CLOSE,
  DAVE_TASKS,
  gateMinutes,
  gateTerms,
  hours,
  peopleMinutes,
  PROMOTION,
  RELEASE,
  sum,
  times,
  type Three,
  tieredGateTerms,
  zero,
} from "./dave-time";
import { DAVE_SHARE, LAUNCH_REVIEW, levelledSchedule, resolveWeight, schedule, selectScope, weightOf } from "./graph";
import { flag, loadUnits, lookup, option, writeBlock, type Execution, type Unit } from "./units";

/** The routing matrix: uncertainty decides who builds a unit. */
export function matrixRoute(u: Pick<Unit, "uncertainty">): Execution {
  return u.uncertainty === 3 ? "human-led" : "agent-fan-out";
}

const weeks = Number(option("weeks", "18"));
/** The merge desk unit: tiered auto-merge switches on when it merges (ADR 0010). */
const MERGE_DESK = "U-118";
const all = await loadUnits();
const errors: string[] = [];
for (const u of all) {
  if (!u.execution) errors.push(`${u.id} has no execution`);
  if (!u.review) errors.push(`${u.id} has no review tier`);
  if (u.execution !== matrixRoute(u) && !u.execution_reason)
    errors.push(`${u.id} is routed ${u.execution} against the matrix (${matrixRoute(u)}) with no execution_reason`);
  if (u.execution === matrixRoute(u) && u.execution_reason)
    errors.push(`${u.id} is on the matrix route but still carries an execution_reason`);
}

// Planned starts and slack from the demo graph (points until artifact 6 adds estimates).
const demoScope = selectScope(all, "demo", false);
const weightName = resolveWeight(option("weight", "auto"), demoScope.units);
const plan = schedule(demoScope.units, demoScope.deps, (u) => weightOf(u, weightName));
const unitLabel = weightName === "pert" ? "days" : "points";
const fmt = (n: number) => (weightName === "pert" ? n.toFixed(1) : String(Math.round(n * 100) / 100));
const slackOf = (id: string) => (plan.isCritical(id) ? 0 : lookup(plan.slack, id));
const byStart = (a: Unit, b: Unit) =>
  lookup(plan.es, a.id) - lookup(plan.es, b.id) || lookup(plan.slack, a.id) - lookup(plan.slack, b.id) || a.id.localeCompare(b.id);
const demo = demoScope.units;
const byId = new Map(all.map((u) => [u.id, u]));
const fanOutDemo = demo.filter((u) => u.execution === "agent-fan-out").sort(byStart);
const firstUnits = new Set(fanOutDemo.slice(0, APPROVAL_MODE_UNITS).map((u) => u.id));

const scopes: { name: string; units: Unit[] }[] = [
  { name: "Demo build (P5, Foundation and Must)", units: demo },
  {
    name: "Shoulds, if the cut order keeps them",
    units: all.filter((u) => u.phase === "P5" && u.mode === "both" && u.priority === "Should"),
  },
  { name: "Real job only (estimated, not built)", units: all.filter((u) => u.phase === "P5" && u.mode === "real-job") },
  { name: "Post-launch tail", units: all.filter((u) => u.phase === "post-launch") },
  { name: "P4 spikes", units: all.filter((u) => u.phase === "P4") },
];

const md: string[] = [];
const line = (s = "") => md.push(s);
line(`Generated by \`bun scripts/plan/execution-model.ts --weeks ${weeks}${option("weight", "auto") !== "auto" ? ` --weight ${weightName}` : ""}\`. Do not edit by hand.`);
line();
line(
  `**Checks.** ${errors.length ? `${errors.length} errors:` : "Every unit is routed and has a review tier; every unit off the matrix has a reason, and no unit on it carries one."}`,
);
for (const e of errors) line(`- ${e}`);
line();

const execs: Execution[] = ["human-only", "human-led", "agent-fan-out"];
line(
  `**Routing by complexity (C) and uncertainty (U)**, all ${all.length} units. Each cell: the matrix route, then how many units went to each route.`,
);
line();
line(`| | U1 | U2 | U3 |`);
line(`|---|---|---|---|`);
for (const c of [1, 2, 3] as const) {
  const cells = ([1, 2, 3] as const).map((uu) => {
    const xs = all.filter((u) => u.complexity === c && u.uncertainty === uu);
    if (!xs.length) return "none";
    const counts = execs.map((e) => [e, xs.filter((u) => u.execution === e).length] as const).filter(([, n]) => n > 0);
    return `${matrixRoute({ uncertainty: uu })}: ${counts.map(([e, n]) => `${n} ${e}`).join(", ")}`;
  });
  line(`| C${c} | ${cells.join(" | ")} |`);
}
line();

line(`**Routes by scope:**`);
line();
line(`| Scope | Units | Human-only | Human-led | Agent fan-out | Critical review |`);
line(`|---|---|---|---|---|---|`);
for (const s of scopes) {
  const n = (e: Execution) => s.units.filter((u) => u.execution === e).length;
  line(
    `| ${s.name} | ${s.units.length} | ${n("human-only")} | ${n("human-led")} | ${n("agent-fan-out")} | ${s.units.filter((u) => u.review === "critical").length} |`,
  );
}
line();

const overrides = all.filter((u) => u.execution !== matrixRoute(u));
line(`**Off the matrix** (${overrides.length} units; each needs a reason):`);
line();
line(`| Unit | Title | C | U | Matrix | Routed | Why |`);
line(`|---|---|---|---|---|---|---|`);
for (const u of overrides)
  line(`| ${u.id} | ${u.title} | ${u.complexity} | ${u.uncertainty} | ${matrixRoute(u)} | ${u.execution} | ${u.execution_reason ?? ""} |`);
line();

const onMatrixHuman = all.filter((u) => u.execution !== "agent-fan-out" && u.execution === matrixRoute(u));
line(
  `**Human-led by the matrix** (uncertainty 3): ${onMatrixHuman.map((u) => `${u.id} ${u.title}${u.phase === "P4" ? " (P4 spike)" : u.mode === "real-job" ? " (real job only)" : ""}`).join("; ")}.`,
);
line();

const critical = all.filter((u) => u.review === "critical" && u.execution === "agent-fan-out");
const criticalDemo = critical.filter((u) => demo.includes(u));
line(
  `**Fan-out units on the critical review tier** (${criticalDemo.length} in the demo build, ${critical.length} with the Shoulds; they write money rows, take a lock or add code inside a transaction that holds one, grant or check access, compute the amounts charged or refunded, or carry the real-database race tests for them): ${critical.map((u) => u.id).join(", ")}.`,
);
line();

const needsDave = (u: Unit) => u.execution !== "agent-fan-out";
const lane = levelledSchedule(demo, demoScope.deps, plan.weight, plan, needsDave);
const daveShare = (u: Unit) => (u.execution === "human-only" ? 1 : DAVE_SHARE.m);
const laneLikely = levelledSchedule(demo, demoScope.deps, plan.weight, plan, needsDave, daveShare);
line(
  `**The Dave lane.** The human-led and human-only units share one Dave. Run one at a time, the demo build finishes at ${fmt(lane.length)} ${unitLabel} against the graph's ${fmt(plan.length)}, with Dave busy for ${fmt(lane.daveBusy)} of them. If agents carry the last ${Math.round((1 - DAVE_SHARE.m) * 100)}% of each human-led unit (the likely share), it finishes at ${fmt(laneLikely.length)}. ${weightName === "pert" ? "Gate time is not on this lane yet; artifact 7 adds it." : "Gate time is not on this lane in points; artifact 7 adds it once the units carry days."}`,
);
line();
line(`Dave's order (when he is free, he takes the ready unit with the lowest latest start; then the least slack):`);
line();
line(`| # | Unit | Title | Graph start | Slack | Lane start | Weight | Why human |`);
line(`|---|---|---|---|---|---|---|---|`);
lane.daveOrder.forEach((id, i) => {
  const u = lookup(byId, id);
  line(
    `| ${i + 1} | ${id} | ${u.title} | ${fmt(lookup(plan.es, id))} | ${fmt(slackOf(id))} | ${fmt(lookup(lane.start, id))} | ${fmt(lookup(plan.weight, id))} | ${u.execution_reason ?? "uncertainty 3"} |`,
  );
});
line();

line(`**Acceptance that needs people** (Dave's time inside fan-out units):`);
line();
line(`| Unit | Check | Minutes (o, m, p) |`);
line(`|---|---|---|`);
for (const u of all.filter((x) => x.acceptance_by_people)) {
  const a = u.acceptance_by_people;
  if (a) line(`| ${u.id} | ${a.what} | ${a.minutes.o}, ${a.minutes.m}, ${a.minutes.p} |`);
}
line();

// ---------- Dave's time ----------
// The plan of record is tiered auto-merge (ADR 0010, amended 2026-10-20): agents merge on their own verdicts, so a fan-out
// unit costs Dave only escalations, plus a diff read in the weekly promotion batch when it is on the critical tier. The
// old rule, where Dave reads and merges every unit (approval mode for the first units, then auto), stays as the comparison.
const fanOut = (units: Unit[]) => units.filter((u) => u.execution === "agent-fan-out");
const gate = (units: Unit[], approvalFor: (u: Unit) => boolean) => sum(fanOut(units).map((u) => gateMinutes(u, approvalFor(u))));
const tieredGate = (units: Unit[]) => sum(fanOut(units).map((u) => sum(Object.values(tieredGateTerms(u)))));
const batchReads = (units: Unit[]) => sum(fanOut(units).map(batchReadMinutes));
const closes = (units: Unit[]) => times(CLOSE, units.filter((u) => u.execution !== "agent-fan-out").length);
const people = (units: Unit[]) => sum(units.map(peopleMinutes));
const promotions = times(PROMOTION, weeks);

line(`**Dave's gate time** (fan-out gates, plus the close on human-led units; minutes are assumptions):`);
line();
line(`| Scope | Fan-out units | Tiered auto-merge (plan of record) | Dave merges all, auto after the first ${APPROVAL_MODE_UNITS} | People checks |`);
line(`|---|---|---|---|---|`);
for (const s of scopes.filter((x) => x.name !== "P4 spikes")) {
  const tiered = sum([tieredGate(s.units), batchReads(s.units), closes(s.units)]);
  const old = add(
    gate(s.units, (u) => firstUnits.has(u.id)),
    closes(s.units),
  );
  line(`| ${s.name} | ${fanOut(s.units).length} | ${hours(tiered)} | ${hours(old)} | ${hours(people(s.units))} |`);
}
line();
line(
  `The tiered column leaves out the weekly promotion itself, ${hours(promotions)} over ${weeks} weeks, which is in the total below. Units merged before ${MERGE_DESK} (the merge desk) would go through Dave; none is a fan-out unit, because U-001 depends on it.`,
);
line();
const termTotals = new Map<string, Three>();
for (const u of fanOut(demo)) for (const [k, v] of Object.entries(tieredGateTerms(u))) termTotals.set(k, add(termTotals.get(k) ?? zero, v));
termTotals.set("critical-tier diff reads in the promotion batch", batchReads(demo));
termTotals.set("weekly promotion", promotions);
termTotals.set("close on human-led units", closes(demo));
line(`**Where the demo gate time goes** (tiered auto-merge):`);
line();
line(`| Term | Hours |`);
line(`|---|---|`);
for (const [k, v] of [...termTotals].sort((a, b) => b[1].m - a[1].m)) if (v.m > 0) line(`| ${k} | ${hours(v)} |`);
line();
line(`Likely hours, with the sum of the optimistic and pessimistic points in brackets; the true range is narrower, since not every unit lands at its extreme.`);
line();

const share = (id: string) => Math.max(0, 1 - lookup(plan.ef, id) / plan.length);
const ciWeeks = weeks * share("U-105");
const releases = Math.ceil(weeks * share("U-103")); // weekly after U-103's first promotion (its people check), plus the launch release
const recurring = [
  { what: "Merge the PM's bookkeeping PR", count: weeks, unit: "weeks", minutes: BOOKKEEPING },
  {
    what: "Triage red nightly or main CI runs; merge the fix-forward PRs (from U-105's merge)",
    count: ciWeeks,
    unit: "weeks",
    minutes: CI_TRIAGE,
  },
  {
    what: "Production promotions after U-103's first one (weekly, plus the launch release)",
    count: releases,
    unit: "releases",
    minutes: RELEASE,
  },
];
line(`**Recurring work over ${weeks} P5 weeks** (start points from the planned schedule; the weeks are artifact 6's likely build length):`);
line();
line(`| Work | Count | Minutes each (o, m, p) | Total |`);
line(`|---|---|---|---|`);
for (const r of recurring)
  line(
    `| ${r.what} | ${r.count.toFixed(1)} ${r.unit} | ${r.minutes.o}, ${r.minutes.m}, ${r.minutes.p} | ${hours(times(r.minutes, r.count))} |`,
  );
line();

const tasks = (scope: "demo" | "real-job", phase: "P4" | "P5" = "P5") => DAVE_TASKS.filter((t) => t.scope === scope && t.phase === phase);
line(
  `**Dave's tasks outside the units:** before the build (P4) ${hours(sum(tasks("demo", "P4").map((t) => t.minutes)))}; during the build ${hours(sum(tasks("demo").map((t) => t.minutes)))}; the real job adds ${hours(sum(tasks("real-job").map((t) => t.minutes)))}.`,
);
line();
line(`| Task | When | Scope | Phase | Minutes (o, m, p) |`);
line(`|---|---|---|---|---|`);
for (const t of DAVE_TASKS) line(`| ${t.task} | ${t.when} | ${t.scope} | ${t.phase} | ${t.minutes.o}, ${t.minutes.m}, ${t.minutes.p} |`);
line();

const demoTiered = sum([tieredGate(demo), batchReads(demo), promotions, closes(demo)]);
const demoTotal = sum([demoTiered, people(demo), ...recurring.map((r) => times(r.minutes, r.count)), ...tasks("demo").map((t) => t.minutes)]);
line(
  `**Demo build, Dave's time outside the human-led units** (tiered auto-merge): ${hours(demoTotal)}, about ${(demoTotal.m / 60 / weeks).toFixed(1)} h a week over ${weeks} weeks. The human-led units come on top, at ${DAVE_SHARE.o * 100} to ${DAVE_SHARE.p * 100}% of their elapsed days (lever 3); artifact 7 schedules both.`,
);
line();

line(
  `**Gates on the critical path.** Under tiered auto-merge a path unit waits for its agent checks, not for Dave: critical-tier units land on \`integration\` and their dependents build on them there. Dave's batch read happens off the path, except that the launch review (${LAUNCH_REVIEW}) waits for the last promotion. Escalations on the path's fan-out units (${plan.path.filter((id) => lookup(byId, id).execution === "agent-fan-out").join(", ")}) are the only gate time on it.`,
);
line();

const firstCritical = fanOutDemo.filter((u) => u.review === "critical").slice(0, 2);
const firstC3 = fanOutDemo.find((u) => u.complexity === 3);
line(
  `**Calibration points.** Refit ESCALATION after the first ${APPROVAL_MODE_UNITS} fan-out merges (${fanOutDemo.slice(0, APPROVAL_MODE_UNITS).map((u) => u.id).join(", ")}); CRITICAL_READ and PROMOTION after the first two promotions, which carry the first critical-tier units (${firstCritical.map((u) => u.id).join(", ")}); the C3 rows after the first C3 fan-out merge (${firstC3?.id ?? "none"}). After the freeze, a refit is a delta-log line; the frozen estimate stays.`,
);
line();

line(`<details><summary>Every unit: route, review tier, Dave's likely gate minutes</summary>`);
line();
line(`| Unit | Title | C | U | Route | Review | Tiered | Dave merges all (auto) |`);
line(`|---|---|---|---|---|---|---|---|`);
for (const u of all) {
  const f = u.execution === "agent-fan-out";
  line(
    `| ${u.id} | ${u.title} | ${u.complexity} | ${u.uncertainty} | ${u.execution} | ${u.review} | ${f ? sum([...Object.values(tieredGateTerms(u)), batchReadMinutes(u)]).m : "share of days"} | ${f ? gateMinutes(u, false).m : "share of days"} |`,
  );
}
line();
line(`</details>`);

const output = md.join("\n");
const target = option("write", "");
if (target) {
  await writeBlock(target, "execution-model", "report", output);
  console.error(`wrote the report to ${target}`);
} else if (!flag("quiet")) {
  console.log(output);
}
process.exit(errors.length ? 1 : 0);
